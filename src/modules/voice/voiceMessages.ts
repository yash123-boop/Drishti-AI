export type VoiceMessageKey = keyof (typeof voiceMessages)['en-IN'];
export type VoiceMessageParameters = Record<string, string | number>;

const completeVoiceMessages: Record<
  VoiceLanguage,
  Record<VoiceMessageKey, string>
> = voiceMessages;

export function getVoiceMessage(
  language: string,
  key: VoiceMessageKey,
  parameters: VoiceMessageParameters = {}
): string {
  const messages = completeVoiceMessages[language as VoiceLanguage] ?? completeVoiceMessages['en-IN'];
  const template = messages[key];

  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(parameters[name] ?? placeholder)
  );
}
