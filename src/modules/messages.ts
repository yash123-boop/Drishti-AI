export type MessageKey = keyof typeof messages.en;

export function getMessages(language: string) {
  return language.toLowerCase().startsWith('hi') ? messages.hi : messages.en;
}

export function formatMessage(message: string, values: Record<string, string>): string {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? '');
}
